import EMFBase
import Testing

@testable import ECore

/// Tests of the mapping of Stratego signatures to classifiers.
@Suite("Stratego signatures")
struct SDF3SignatureTests {
    /// A signature with every kind of entry.
    static let signature = """
        module signatures/Records-sig

        imports signatures/Base-sig

        signature
          sorts Record Field IntConst
          constructors
            Record : ID * List(Field) -> Record
            Field  : ID * Option(Value) -> Field
            Empty  : Record
            Pair   : Value * Value -> Value
            Num    : IntConst -> Value
            Wrap   : a -> Value
            Count  : int * Real * string -> Value
                   : Record -> Value
                   : string -> IntConst
                   : string -> ID
            Value-Plhdr : Value
            Value-Plhdr : COMPLETION-INSERTION -> Value

        rules
          normalise : Pair(x, y) -> Pair(y, x)
        """

    /// Sorts become abstract classes and constructors concrete subclasses.
    @Test func constructors() throws {
        let result = read(Self.signature)
        #expect(result.errors.isEmpty)
        #expect(result.package.name == "Records_sig")
        #expect(result.eClass("Record")?.isAbstract == true)
        let record = try #require(result.eClass("RecordRecord"))
        #expect(record.superTypeNames == ["Record"])
        #expect(record.featureNames == ["id1", "field1"])
        #expect(record.anyReference("field1")?.upperBound == -1)
        #expect(record.anyReference("field1")?.lowerBound == 0)
        let field = try #require(result.eClass("FieldField"))
        #expect(field.anyReference("value1")?.lowerBound == 0)
        #expect(field.anyReference("value1")?.upperBound == 1)
        #expect(result.eClass("Empty")?.featureNames == [])
        #expect(result.eClass("Empty")?.superTypeNames == ["Record"])
        #expect(result.validationErrors.isEmpty)
    }

    /// Built-in types, type variables, injections and lexical sorts map as documented.
    @Test func typesAndInjections() throws {
        let result = read(Self.signature)
        let count = try #require(result.eClass("Count"))
        #expect(count.anyAttribute("int1")?.eType.name == "EInt")
        #expect(count.anyAttribute("real1")?.eType.name == "EDouble")
        #expect(count.anyAttribute("string1")?.eType.name == "EString")
        #expect(result.eClass("Wrap")?.anyReference("a1")?.eType.name == "EObject")
        #expect(result.eClass("Record")?.superTypeNames == ["Value"])
        #expect(result.package.getEDataType("IntConst") != nil)
        #expect(result.package.getEDataType("ID") != nil)
        #expect(result.eClass("Num")?.anyAttribute("intConst1")?.eType.name == "IntConst")
    }

    /// Placeholder constructors generated by Spoofax are left out, as are rules.
    @Test func generatedEntriesAndRulesAreSkipped() throws {
        let result = read(Self.signature)
        #expect(result.package.getClassifier("Value_Plhdr") == nil)
        #expect(result.package.getClassifier("COMPLETION_INSERTION") == nil)
        #expect(result.package.getClassifier("normalise") == nil)
        #expect(result.diagnostics(.undefinedSort).isEmpty)
    }

    /// Overloaded constructors are renamed; exact repetitions are read once.
    @Test func overloading() throws {
        let result = read("""
            module overloads
            signature constructors
              Var : ID -> Exp
              Var : ID * ID -> Exp
              Var : ID -> Type
              Var : ID -> Exp
              : string -> ID
            """)
        #expect(result.diagnostics(.constructorRenamed).count == 2)
        #expect(result.eClass("Var")?.featureNames == ["id1"])
        #expect(result.eClass("VarExp")?.featureNames == ["id1", "id2"])
        #expect(result.eClass("VarType")?.superTypeNames == ["Type"])
        #expect(result.validationErrors.isEmpty)
    }

    /// A signature on one line with `signature constructors` reads like a multi-line one.
    @Test func compactHeader() throws {
        let result = read("module compact\nsignature constructors\n  True : Bool\n  False : Bool\n  Not : Bool -> Bool")
        #expect(result.errors.isEmpty)
        #expect(result.package.eClassifiers.map(\.name) == ["Bool", "True", "False", "Not"])
        #expect(result.eClass("Not")?.featureNames == ["bool1"])
    }

    /// Wildcard imports are read, and a lower-case result sort is a sort.
    @Test func wildcardImportAndLowerCaseSort() throws {
        let result = read("module lib\nimports util/-\nsignature constructors\n  Float : term\n  Box : a -> term")
        #expect(result.errors.isEmpty)
        #expect(result.diagnostics.isEmpty)
        #expect(result.eClass("term")?.isAbstract == true)
        #expect(result.eClass("Float")?.superTypeNames == ["term"])
        #expect(result.eClass("Box")?.anyReference("a1")?.eType.name == "EObject")
        #expect(result.outline.first?.children.first?.children.first?.name == "util/-")
    }
}
